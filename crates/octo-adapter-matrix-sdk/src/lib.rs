/// Redact a token for safe display. R2-L14: the previous form
/// ("first 8 chars + ***") gave every long token the same output
/// length, which was misleading — a 200-char token and a 9-char
/// token looked identical in logs. The new form shows
/// "first 8 + ... + last 4" for long tokens (12 chars or more),
/// the full token + "***" for medium (9-11 chars), and "***" for
/// short (≤ 8 chars or empty).
///
/// R7-M2: a previous version of this docstring claimed the
/// medium branch was "first 8 + ***"; the actual implementation
/// in `redact_token` below emits the full token + "***" for
/// medium tokens so an operator inspecting logs can correlate
/// a 9-to-11-char token against the homeserver's UI without
/// losing the tail. The docstring now matches the
/// implementation. The "first 8 + ***" form (a) would have
/// truncated 9-11 char tokens at byte 8, hiding the
/// distinguishing chars, and (b) would have been a near-duplicate
/// of the long branch's head — defeating the purpose of the
/// length-based tiering.
///
/// R2-H2: byte-based slicing is replaced with char-based slicing
/// so a multi-byte UTF-8 boundary can't panic. A token that is
/// exclusively ASCII has the same output as before; a token with
/// non-ASCII characters gets the first 8 / last 4 CHARS instead
/// of the first 8 / last 4 BYTES.
///
/// R5-L1: this is one of FOUR `redact_*` implementations across
/// the four mission crates. Each site has a deliberately
/// different format policy because each display context calls
/// for a different balance of brevity and operator-recognizability:
///
/// - `crates/octo-adapter-matrix-sdk/src/lib.rs` (THIS FILE) —
///   free-form diagnostic output (error messages, debug logs).
///   Uses a 3-tier form (first8...last4 / all*** / ***) so
///   operators can correlate the start AND end of a long token
///   against the homeserver's UI.
/// - `crates/octo-matrix-onboard-core/src/lib.rs:access_token_preview` — the
///   one-time "logged in" confirmation message
///   (`Session::access_token_preview`). Uses a 2-tier form
///   (first8...last4 / first4...) that reveals slightly more
///   of short tokens.
/// - `crates/octo-matrix-onboard/src/modes/session.rs:redact_token` —
///   tabular `session list` output. R6-M2 fixed the byte-slicing
///   (R2-H2 missed this site) so the slice is now char-boundary
///   safe. Shape: `first ≤8 bytes + ***` / `***`.
/// - `crates/octo-matrix-onboard/src/logging.rs:redact_value` —
///   tracing-subscriber `FormatEvent` redaction. Char-boundary-
///   walked byte slice (the only site that walks back, so a
///   4S recovery key with non-ASCII bytes can't panic).
///   Shape: `first ≤8 bytes + ***` / `***`.
///
/// If you change this implementation, audit the other three for
/// consistency. The per-site policies are intentional; the
/// cross-reference is the missing piece a future maintainer
/// needs to avoid silent divergence.
fn redact_token(token: &str) -> String {
    let chars: Vec<char> = token.chars().collect();
    if chars.len() >= 12 {
        let head: String = chars[..8].iter().collect();
        let tail: String = chars[chars.len() - 4..].iter().collect();
        format!("{head}...{tail}")
    } else if chars.len() > 8 {
        let head: String = chars.iter().collect();
        format!("{head}***")
    } else {
        "***".to_string()
    }
}

/// Errors that `MatrixAdapter::new` can surface. R1-L14: the previous
/// shape (`Result<Self, String>`) forced the C ABI export below
/// to discard the error string. This structured type lets cdylib hosts
/// read a stable error category via `last_error()`.
#[derive(Debug, thiserror::Error)]
pub enum MatrixAdapterError {
    #[error("session load: {0}")]
    SessionLoad(String),
    #[error("invalid user_id '{user_id}': {source}")]
    InvalidUserId {
        user_id: String,
        source: matrix_sdk::ruma::IdParseError,
    },
    #[error("failed to create tokio runtime: {0}")]
    Runtime(String),
    #[error("client build: {0}")]
    ClientBuild(String),
    #[error("session restore: {0}")]
    SessionRestore(String),
    /// R2-M4: a writeback failure is conceptually distinct from a
    /// session-load failure. Pattern-matching on
    /// `MatrixAdapterError` was treating a snapshot-drift writeback
    /// as a session-load problem; the new variant routes it to
    /// the right bucket.
    #[error("writeback failed: {0}")]
    WritebackFailed(String),
}

/// Matrix adapter configuration.
///
/// The required `user_id` / `device_id` / `access_token` fields are
/// captured by `octo-matrix-onboard` (mission 0850h-a). The optional
/// `refresh_token` is populated when the homeserver issues one.
///
/// `passphrase` (mission 0850h-b) is an optional field that, when
/// `Some`, is mixed into the SDK's crypto-store key derivation so the
/// on-disk Olm/Megolm session material is encrypted at rest. When
/// `None`, the SDK falls back to the platform default (system keyring
/// on supported platforms, in-memory otherwise). It is never serialized
/// back to disk — the operator supplies it on the CLI as
/// `--passphrase-stdin` and the adapter holds it in memory only.
///
/// `config_path` / `force_writeback` (mission 0850h-c) control the
/// on-disk writeback of rotated `access_token` / `refresh_token`
/// pairs: when `config_path` is non-empty, the adapter writes the
/// rotated pair back to it (atomic rename + flock) so long-running
/// daemons survive a process restart without re-onboarding. When
/// `config_path` is empty, writeback is disabled (in-memory or
/// read-only deployments). `force_writeback` skips the
/// before-snapshot check that protects against two long-running
/// processes clobbering each other's token rotations.
/// Validate a `user_id` MXID at deserialization. R2-M2: the
/// previous shape deferred validation to `MatrixAdapter::new`,
/// which meant a malformed MXID silently passed JSON
/// deserialization for any consumer that did not build an adapter.
/// The Matrix MXID grammar is well-defined (RFC-0850 §MXID); we
/// reject malformed values at the boundary.
fn deserialize_mxid<'de, D>(deserializer: D) -> std::result::Result<String, D::Error>
where
    D: serde::Deserializer<'de>,
{
    let raw = String::deserialize(deserializer)?;
    matrix_sdk::ruma::OwnedUserId::try_from(raw.as_str())
        .map_err(|e| serde::de::Error::custom(format!("invalid MXID {raw:?}: {e}")))?;
    Ok(raw)
}

#[derive(Clone, Deserialize, serde::Serialize)]
pub struct MatrixConfig {
    /// Matrix homeserver URL
    pub homeserver_url: String,
    /// Authenticated user (e.g. `@bot:matrix.example.com`).
    /// Required by `restore_session` — must match `access_token`.
    /// R2-M2: validated at deserialization via
    /// `OwnedUserId::try_from`. A malformed MXID surfaces as a
    /// `serde` error at the boundary, not later as a confusing
    /// server-side error.
    #[serde(deserialize_with = "deserialize_mxid")]
    pub user_id: String,
    /// Device ID (e.g. `ABCDEFGHIJ`). Required by `restore_session`.
    /// R2-M2 (asymmetry): the Matrix spec makes device IDs opaque
    /// (any string is valid), so ruma's `OwnedDeviceId::validate`
    /// is a no-op. We do NOT validate here, mirroring ruma's own
    /// `From<&&str>` impl. Mismatched validation asymmetry between
    /// `user_id` and `device_id` is intentional.
    pub device_id: String,
    /// Access token for authentication (long-lived or
    /// refresh-rotated). Never serialized back to disk; the on-disk
    /// rotation path is mission 0850h-c.
    #[serde(skip_serializing)]
    pub access_token: String,
    /// Optional refresh token issued by the homeserver. When
    /// present, the adapter calls `oauth.refresh_token(...)` on 401
    /// and holds the rotated pair in memory. None when the
    /// homeserver doesn't issue refresh tokens (some password
    /// flows).
    #[serde(default, skip_serializing_if = "Option::is_none", skip_serializing)]
    pub refresh_token: Option<String>,
    /// Optional passphrase for the SDK's crypto store. When `Some`
    /// AND `config_path` is non-empty, the SDK derives an encryption
    /// key from it for the on-disk Olm/Megolm session material
    /// (mission 0850h-b). When `passphrase` is `Some` but
    /// `config_path` is empty, the gate at `MatrixAdapter::new`
    /// (`MatrixAdapter::new`) does NOT wire `sqlite_store` — the SDK
    /// falls back to the default in-memory crypto store. This is a
    /// documented R1-H8 / R2-M5 / R2-H1 design choice (see the
    /// adapter gate for the rationale). When `None`, the SDK uses
    /// the default in-memory store regardless of `config_path`.
    /// Never serialized back to disk — supplied on the CLI as
    /// `--passphrase-stdin`.
    #[serde(default, skip_serializing_if = "Option::is_none", skip_serializing)]
    pub passphrase: Option<String>,
    /// On-disk location of the config file. When the SDK rotates the
    /// access/refresh-token pair on a 401 response, the adapter writes
    /// the rotated pair back to this path (mission 0850h-c). When
    /// `PathBuf::new()` (the default), writeback is disabled — useful
    /// for in-memory or read-only deployments.
    #[serde(default)]
    pub config_path: PathBuf,
    /// Skip the before-snapshot check on writeback (mission 0850h-c).
    /// The default `false` protects against two long-running processes
    /// silently clobbering each other's token rotations; set to `true`
    /// from the host process when only one writer is expected.
    #[serde(default)]
    pub force_writeback: bool,
    /// When `true` (the default), the adapter loads the session from
    /// the multi-account stoolap store when `session_store_path` is
    /// non-empty. When `false`, the adapter reads the legacy
    /// single-file config at `config_path` (mission 0850h-a / 0850h-c
    /// behavior; useful for backward compatibility with deployments
    /// that pre-date the store).
    #[serde(default = "default_true")]
    pub use_session_store: bool,
    /// On-disk location of the multi-account stoolap store (mission
    /// 0850h-d). When `PathBuf::new()`, the store path defaults to
    /// the per-platform `ProjectDirs("com", "cipherocto", "cipherocto")
    /// / data_dir() / sessions.db` location. Ignored when
    /// `use_session_store` is `false`.
    #[serde(default)]
    pub session_store_path: PathBuf,
    /// Room IDs to monitor
    pub rooms: Vec<String>,
}

fn default_true() -> bool {
    true
}

impl std::fmt::Debug for MatrixConfig {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("MatrixConfig")
            .field("homeserver_url", &self.homeserver_url)
            .field("user_id", &self.user_id)
            .field("device_id", &self.device_id)
            .field("access_token", &redact_token(&self.access_token))
            .field(
                "refresh_token",
                &self.refresh_token.as_deref().map(redact_token),
            )
            .field(
                "passphrase",
                &self.passphrase.as_deref().map(|_| "***".to_string()),
            )
            // R22-L1: the previous hand-rolled Debug omitted the
            // 4 non-secret adapter-only fields (config_path,
            // force_writeback, use_session_store, session_store_path),
            // so an operator running `dbg!(config)` would not see
            // the on-disk config path or the multi-account store
            // wiring. None of the 4 are secret (they're a path
            // or a bool), so they render directly. The passphrase
            // is the only secret field that needs redaction, and
            // it's already redacted above.
            .field("config_path", &self.config_path)
            .field("force_writeback", &self.force_writeback)
            .field("use_session_store", &self.use_session_store)
            .field("session_store_path", &self.session_store_path)
            .field("rooms", &self.rooms)
            .finish()
    }
}

/// Matrix adapter using matrix-rust-sdk.
#[derive(Debug)]
pub struct MatrixAdapter {
    config: MatrixConfig,
    client: Client,
    // R2-L5: the embedded `tokio::runtime::Runtime` is used to
    // drive the `session_loader::load` future and the SDK's
    // crypto-store initialization during `MatrixAdapter::new`.
    // After construction, the SDK owns its own internal
    // background-task machinery — but we still keep the runtime
    // alive on the struct: dropping it would invalidate any
    // timer or interval handles the SDK created against it. The
    // runtime drops with the adapter; no explicit shutdown
    // needed.
    #[allow(dead_code)] // Held for SDK lifetime; read only via Drop.
    runtime: tokio::runtime::Runtime,
    /// Sync token for incremental /sync (ZeroClaw pattern).
    next_batch: std::sync::Mutex<Option<String>>,
    /// Cached bot user ID (e.g., @bot:server)
    user_id: std::sync::Mutex<Option<String>>,
    /// R3-H1: last-known on-disk snapshot of the config file, used
    /// by `persist_session_to_disk` as the `on_disk_before` argument
    /// to `config_writer::writeback`. Without this, the second
    /// writeback after a token rotation would always fail with
    /// `SnapshotMismatch` because `self.config.access_token` is the
    /// original token (not the rotated one written in the previous
    /// writeback). The snapshot is initialized at construction from
    /// the actual on-disk file (or `None` if no on-disk config) and
    /// is updated after each successful writeback (and on the no-op
    /// fast path, in case the file was rewritten by a sibling
    /// process between our reads).
    last_on_disk_snapshot: std::sync::Mutex<Option<config_writer::OnDiskConfig>>,
}

// R2-L18: compile-time assertion that `MatrixAdapter` is
// `Send + Sync`. The struct holds a `tokio::runtime::Runtime` and
// a `Client`, both of which are internally `Send + Sync`, but a
// future change (e.g., adding a `Rc<...>` field) could silently
// regress this. A `static_assertions::assert_impl_all!` would be
// the conventional Rust crate, but adding a dev-dep just for one
// assertion is heavier than the in-line form. The block runs at
// compile time; if `MatrixAdapter` ever loses `Send` or `Sync`,
// the build fails here with a clear "the trait `Send` is not
// implemented for `MatrixAdapter`" message pointing at this
// const, not at some opaque `Client` internal.
const _: fn() = || {
    fn assert_send<T: Send>() {}
    fn assert_sync<T: Sync>() {}
    assert_send::<MatrixAdapter>();
    assert_sync::<MatrixAdapter>();
};

impl MatrixAdapter {
    /// Create a new Matrix adapter from config.
    ///
    /// Builds a tokio runtime, initializes the matrix-sdk Client, and
    /// restores the session from the config. The actual session
    /// material (access / refresh tokens) is resolved by
    /// `session_loader::load`, which honors the new mission 0850h-d
    /// `use_session_store` field:
    ///
    /// - `use_session_store = true` (the default): load the row from
    ///   the multi-account stoolap store at `session_store_path` (or
    ///   the per-platform default).
    /// - `use_session_store = false` AND `config_path` is set: read
    ///   the legacy 0850h-a / 0850h-c JSON file.
    /// - `use_session_store = false` AND `config_path` is empty: use
    ///   the config's in-memory `access_token` / `refresh_token`
    ///   fields directly (cdylib hosts that build a MatrixConfig from
    ///   a config blob without persisting it).
    ///
    /// On 401 the SDK's `handle_refresh_tokens()` (wired in the
    /// `Client::builder()` call below) keeps the rotated pair in
    /// memory. The on-disk config is NOT updated by the SDK; the
    /// host process drives the actual writeback via
    /// `persist_session_to_disk(force_writeback: bool)`
    /// (mission 0850h-c; signature changed in R6-M1 — the
    /// per-call `force_writeback` arg is OR'd with the
    /// config-level `self.config.force_writeback` setting).
    pub fn new(config: MatrixConfig) -> Result<Self, MatrixAdapterError> {
        use matrix_sdk::authentication::matrix::MatrixSession;
        use matrix_sdk::ruma::{OwnedDeviceId, OwnedUserId};
        use matrix_sdk::{SessionMeta, SessionTokens};

        let runtime = tokio::runtime::Builder::new_multi_thread()
            .enable_all()
            .build()
            .map_err(|e| MatrixAdapterError::Runtime(e.to_string()))?;

        // Mission 0850h-d: resolve the actual session material via
        // the loader. The returned `LoadedSession` overrides the
        // config's `access_token` / `refresh_token` for the SDK
        // restore call (the original config is kept on `self.config`
        // for writeback / display purposes). R1-M23: `load` is
        // `async`; we drive it on the multi_thread runtime this
        // function just built (the loader no longer builds a
        // per-call `current_thread` runtime internally).
        //
        // R19-L1: route the typed `LoadError` variants through
        // distinct `SessionLoad` messages so the I/O vs parse
        // distinction is visible to the host's `last_error()`
        // (the previous shape `LoadError::File(String)` collapsed
        // them into a single opaque string, asymmetric with the
        // typed `Store(#[source] SessionStoreError)` variant).
        let loaded = runtime
            .block_on(session_loader::load(&config))
            .map_err(|e| match e {
                session_loader::LoadError::FileIo { path, source } => {
                    MatrixAdapterError::SessionLoad(format!("read config {:?}: {}", path, source))
                }
                session_loader::LoadError::FileParse(source) => {
                    MatrixAdapterError::SessionLoad(format!("parse config: {}", source))
                }
                other => MatrixAdapterError::SessionLoad(other.to_string()),
            })?;

        let user_id = OwnedUserId::try_from(loaded.user_id.as_str()).map_err(
            |e: matrix_sdk::ruma::IdParseError| MatrixAdapterError::InvalidUserId {
                user_id: loaded.user_id.clone(),
                source: e,
            },
        )?;
        let device_id = OwnedDeviceId::from(loaded.device_id.as_str());

        let session = MatrixSession {
            meta: SessionMeta { user_id, device_id },
            tokens: SessionTokens {
                access_token: loaded.access_token,
                refresh_token: loaded.refresh_token,
            },
        };

        // Mission 0850h-b: wire the SDK's `sqlite_store` with the
        // operator-supplied `passphrase` so the on-disk Olm/Megolm
        // material is encrypted at rest. R1-H8 fixed the prior
        // "passphrase is held in memory, host process will pass to
        // `.sqlite_store` directly" doc-claim that was
        // never realised in code.
        //
        // The store path is derived from `config_path`:
        // `<dir>/<basename>.store.sqlite`. The store is opened
        // ONLY when the operator supplied a passphrase — without a
        // passphrase, the SDK's default in-memory crypto store is
        // good enough for the process lifetime and avoids the
        // matrix-sdk 0.17.0 migration `near "DROP": syntax error`
        // bug that surfaces on a fresh DB. (Future work: file an
        // upstream issue or gate the migration behind a feature.)
        let store_path =
            if config.passphrase.is_some() && !config.config_path.as_os_str().is_empty() {
                let mut p = config.config_path.clone();
                let stem = p
                    .file_stem()
                    .map(|s| s.to_os_string())
                    .unwrap_or_else(|| std::ffi::OsString::from("matrix"));
                p.set_file_name(stem);
                p.set_extension("store.sqlite");
                Some(p)
            } else {
                None
            };

        let homeserver_url = loaded.homeserver_url.clone();
        let passphrase_ref = config.passphrase.as_deref();
        let client = runtime.block_on(async {
            let mut builder = Client::builder()
                .homeserver_url(&homeserver_url)
                // Enable in-memory refresh on 401 when a refresh_token is
                // present. The SDK rotates tokens internally; the on-disk
                // config is left untouched (mission 0850h-c writes back).
                .handle_refresh_tokens();
            // Wire the on-disk crypto store ONLY when a passphrase
            // is set (mission 0850h-b). The SDK's default in-memory
            // store handles the no-passphrase case for the lifetime
            // of the process.
            if let Some(path) = store_path {
                if let Some(parent) = path.parent() {
                    let _ = std::fs::create_dir_all(parent);
                }
                builder = builder.sqlite_store(&path, passphrase_ref);
            }
            let c = builder
                .build()
                .await
                .map_err(|e| MatrixAdapterError::ClientBuild(e.to_string()))?;
            c.restore_session(session)
                .await
                .map_err(|e| MatrixAdapterError::SessionRestore(e.to_string()))?;
            Ok::<_, MatrixAdapterError>(c)
        })?;

        // Cache the bot user_id for self_handle()
        let cached_user = std::sync::Mutex::new(Some(loaded.user_id));

        // R3-H1: capture the actual on-disk snapshot at construction
        // time so `persist_session_to_disk` can later use it as the
        // `on_disk_before` argument. If the file is absent or
        // unparseable, leave the slot as `None` — `writeback` only
        // uses the snapshot under `!force_writeback`, and the
        // FileMissing / serde_json paths there handle the absence.
        // When `config_path` is empty (in-memory deployments) the
        // writeback is a no-op and the snapshot is never consulted.
        let last_on_disk_snapshot = if config.config_path.as_os_str().is_empty() {
            None
        } else {
            match std::fs::read(&config.config_path) {
                Ok(bytes) => serde_json::from_slice::<config_writer::OnDiskConfig>(&bytes).ok(),
                Err(_) => None,
            }
        };

        Ok(Self {
            config,
            client,
            runtime,
            next_batch: std::sync::Mutex::new(None),
            user_id: cached_user,
            last_on_disk_snapshot: std::sync::Mutex::new(last_on_disk_snapshot),
        })
    }

    /// Create from JSON config bytes (used by plugin ABI).
    ///
    /// R2-M12: the on-disk JSON's `config_path` /
    /// `session_store_path` fields are typed as `PathBuf` and
    /// therefore must be valid UTF-8. On Windows where paths are
    /// typically UTF-16, an operator who passes a path with
    /// non-ASCII characters would see a JSON parse error here,
    /// not a "path not found" error from the FS. The adapter
    /// cannot round-trip a non-UTF-8 path through serde_json
    /// without a custom deserializer; documenting the constraint
    /// here so the operator can encode the path differently
    /// (e.g., via a UTF-8 path on a UTF-16 Windows host).
    pub fn from_config_bytes(config: &[u8]) -> Result<Self, MatrixAdapterError> {
        let config: MatrixConfig = serde_json::from_slice(config)
            .map_err(|e| MatrixAdapterError::SessionLoad(format!("Invalid config: {}", e)))?;
        Self::new(config)
    }

    /// Persist the current session to the on-disk config file.
    ///
    /// R1-H1: this is the wired writeback the mission 0850h-c
    /// acceptance criterion required. Host processes call this after
    /// observing a 401 + refresh cycle (e.g., by polling
    /// `client.session_tokens()` or by hooking the SDK's
    /// `SessionChange` event). The function:
    ///
    /// 1. Captures the **current** access/refresh token from the SDK.
    /// 2. Updates `self.config` with the rotated pair.
    /// 3. Calls `config_writer::writeback` against the snapshot
    ///    captured at adapter construction. `force_writeback`
    ///    controls whether the snapshot-drift check is enforced
    ///    (false = refuse on drift; true = clobber).
    /// 4. Surfaces `WritebackError::LockHeld` as a non-fatal warning
    ///    (the host can retry) and `SnapshotMismatch` as a fatal
    ///    "two writers, refusing to clobber" error unless
    ///    `force_writeback` is true.
    ///
    /// When `config_path` is empty, this is a no-op (in-memory or
    /// read-only deployment).
    ///
    /// R6-M1: the C ABI export of this function
    /// (`persist_session_to_disk`, the `extern "C"` shim at the
    /// bottom of this file) takes a per-call `_force_writeback: u8`
    /// override. R2's original ABI signature exposed the parameter
    /// but the implementation ignored it, so a C host that passed
    /// `_force_writeback = 1` expecting a per-call override silently
    /// got the config-level value. The Rust method now takes a
    /// `force_writeback: bool` argument that is OR'd with the
    /// config-level value (the per-call argument is the
    /// "I'm sure, write it" escape hatch; the config-level
    /// `force_writeback` is the long-lived "I own this row" knob).
    /// Pre-R6 callers that pass `self.config.force_writeback`
    /// (matching the old behaviour) get the same semantics.
    pub fn persist_session_to_disk(
        &self,
        force_writeback: bool,
    ) -> Result<config_writer::WritebackOutcome, MatrixAdapterError> {
        if self.config.config_path.as_os_str().is_empty() {
            return Ok(config_writer::WritebackOutcome { written: false });
        }
        let current = self.client.session_tokens().ok_or_else(|| {
            MatrixAdapterError::SessionLoad("client has no session tokens".to_string())
        })?;
        let rotated = {
            let mut cfg = self.config.clone();
            cfg.access_token = current.access_token.clone();
            cfg.refresh_token = current.refresh_token.clone();
            cfg
        };
        // R3-H1: use the last-known on-disk snapshot for the
        // `on_disk_before` argument. Building it from `&&self.config`
        // (the original behaviour) is wrong after the first
        // successful writeback: `self.config.access_token` is the
        // construction-time token, but on-disk holds the rotated
        // token, so the second writeback would always trip
        // `SnapshotMismatch`. If the snapshot slot is empty (no
        // on-disk file at startup, or unparseable) we fall back to
        // building from `&&self.config`, which preserves the original
        // behaviour for first-time writes — the writeback's own
        // FileMissing check handles the "file disappeared" case.
        let on_disk_before = {
            let guard = self
                .last_on_disk_snapshot
                .lock()
                .expect("last_on_disk_snapshot mutex poisoned");
            guard
                .clone()
                .unwrap_or_else(|| config_writer::OnDiskConfig::from_config(&self.config))
        };
        // R6-M1: OR the per-call override with the config-level
        // `force_writeback`. The C ABI is the only caller that
        // passes a non-config value; the integration test passes
        // `false` (matching the config). The OR semantics: if
        // either side says "force", we force. This means a host
        // that sets `config.force_writeback = true` once (e.g.,
        // for a one-shot migration) and then calls the C ABI with
        // `_force_writeback = 0` still gets the force behaviour —
        // which matches the pre-R6 contract.
        let effective_force = force_writeback || self.config.force_writeback;
        let result = config_writer::writeback(
            &self.config.config_path,
            &on_disk_before,
            &rotated,
            effective_force,
        );
        // R3-H1: on success (write OR no-op), refresh the snapshot so
        // the NEXT writeback's `on_disk_before` matches what's
        // actually on disk. We rebuild from `&&rotated` because that's
        // what `writeback` just persisted; on the no-op path it
        // matches the previous snapshot. Doing this under the same
        // lock that we read from is unnecessary because writeback
        // already serialises against itself via the flock; we just
        // need a write here.
        if result.is_ok() {
            let new_snapshot = config_writer::OnDiskConfig::from_config(&rotated);
            *self
                .last_on_disk_snapshot
                .lock()
                .expect("last_on_disk_snapshot mutex poisoned") = Some(new_snapshot);
        }
        match result {
            Ok(outcome) => Ok(outcome),
            Err(config_writer::WritebackError::LockHeld { .. }) => {
                tracing::warn!(
                    path = %self.config.config_path.display(),
                    "config writeback: lock held by another process; rotated pair stays in memory"
                );
                // Non-fatal: return success with `written: false` so
                // the host can retry on the next 401 cycle.
                Ok(config_writer::WritebackOutcome { written: false })
            }
            Err(config_writer::WritebackError::SnapshotMismatch) => Err(
                MatrixAdapterError::WritebackFailed(
                    // R9-L1: replaced the previous non-existent
                    // `--force-writeback` CLI flag reference. The
                    // C ABI host has two mechanisms to force a
                    // writeback: set `force_writeback: true` in
                    // the on-disk config, or pass
                    // `_force_writeback=1` to the C ABI per-call
                    // argument.
                    "config on-disk contents changed; refusing to overwrite (set `force_writeback: true` in the on-disk config, or pass `_force_writeback=1` to the C ABI)"
                        .to_string(),
                ),
            ),
            // RR2: surface `FileMissing` with a distinct, easily
            // matched message so the C ABI export at the bottom
            // of this file can distinguish it from a generic Io
            // failure. The string check at the C boundary is a
            // stopgap — the right fix is plumbing the typed
            // error all the way through, which is a larger
            // refactor.
            Err(config_writer::WritebackError::FileMissing { path }) => Err(
                MatrixAdapterError::WritebackFailed(format!(
                    "writeback: config file {path:?} disappeared between startup and writeback"
                )),
            ),
            Err(e) => Err(MatrixAdapterError::WritebackFailed(format!(
                "writeback: {}",
                e
            ))),
        }
    }

    /// Encode an envelope as base64 with DOT prefix.
    ///
    /// R1-L18: the base64 alphabet is `URL_SAFE_NO_PAD` per
    /// RFC-0850 §3.2 (the DOT wire format). All DOT adapters in
    /// the workspace MUST use the same alphabet for the
    /// encode → transport → decode round-trip to work. The
    /// constant lives here as the single source of truth; if a
    /// second adapter picks a different alphabet, `decode_envelope`
    /// will fail with a "Base64 decode error" on the receiver
    /// side, which is the intended loud-failure mode.
    pub fn encode_envelope(envelope_bytes: &[u8]) -> String {
        format!(
            "DOT/1/{}",
            base64::engine::general_purpose::URL_SAFE_NO_PAD.encode(envelope_bytes)
        )
    }

    /// Decode a DOT-prefixed base64 envelope. See `encode_envelope`
    /// for the alphabet contract.
    pub fn decode_envelope(text: &str) -> Result<Vec<u8>, String> {
        let text = text.trim();
        let b64 = text
            .strip_prefix("DOT/1/")
            .ok_or_else(|| "Missing DOT/1/ prefix".to_string())?;
        base64::engine::general_purpose::URL_SAFE_NO_PAD
            .decode(b64)
            .map_err(|e| format!("Base64 decode error: {}", e))
    }

    /// Compute domain hash for a Matrix room ID.
    ///
    /// Hash input includes platform prefix per RFC-0850 §3.1:
    /// `BLAKE3-256("matrix:{room_id}")`
    ///
    /// R1-L15: trust model. The function does NOT validate that
    /// `room_id` is a well-formed Matrix room ID (`!opaque:server`).
    /// It lowercases the input and feeds it into BLAKE3-256,
    /// which gives a unique hash for every distinct input
    /// regardless of syntactic validity. Callers are trusted
    /// to pass a room ID the SDK can later resolve (a
    /// `MatrixConfig::rooms` value the host process intends
    /// to join). A malicious caller could in principle register
    /// a domain hash that collides with another platform's
    /// domain — but since the hash input includes the
    /// `matrix:` prefix per RFC-0850, cross-platform collision
    /// is impossible (BLAKE3 is a strong hash, so
    /// `BLAKE3("matrix:foo") != BLAKE3("ipfs:foo")` for all
    /// `foo`).
    pub fn domain_hash(room_id: &str) -> [u8; 32] {
        let normalized = room_id.trim().to_lowercase();
        *blake3::hash(format!("matrix:{}", normalized).as_bytes()).as_bytes()
    }

    /// Platform type constant (0x0003 = Matrix).
    pub const PLATFORM_TYPE: u16 = 0x0003;

    /// Maximum payload bytes per event (Matrix limit).
    pub fn max_payload_bytes() -> usize {
        65536
    }

    /// Rate limit: requests per second.
    pub fn rate_limit_per_second() -> u32 {
        100
    }

    /// R2-M15: enumerate all sessions in the multi-account store.
    ///
    /// Returns a vector of `(user_id, device_id, homeserver_url)`
    /// tuples — exactly the keys the loader uses internally to
    /// resolve a row, plus the homeserver URL so the host can
    /// decide whether the session matches its expected deployment.
    ///
    /// `path` may be:
    /// - `Some(p)` with a non-empty path: open the store at `p`.
    /// - `Some(p)` with an empty path: treated as `None`
    ///   (use the per-platform default).
    /// - `None`: open the per-platform default
    ///   (`$XDG_DATA_HOME/cipherocto/sessions.db` on Linux, etc.).
    ///
    /// Tokens are NOT returned — the API only surfaces identity /
    /// routing metadata. To load a specific session's tokens, the
    /// host passes the chosen `(user_id, device_id)` into
    /// `MatrixConfig` and constructs the adapter; the loader
    /// resolves the row at construction time.
    ///
    /// This is `async` (R1-M23 pattern): the host drives it on its
    /// own tokio runtime. Tests that want to call it use
    /// `tokio::runtime::Runtime::block_on(list_sessions(...))`.
    pub async fn list_sessions(
        path: Option<&std::path::Path>,
    ) -> Result<Vec<(String, String, String)>, MatrixAdapterError> {
        use octo_matrix_session_store::{default_store_path, SessionStore, StoolapSessionStore};
        let resolved = match path {
            Some(p) if !p.as_os_str().is_empty() => p.to_path_buf(),
            _ => {
                default_store_path().map_err(|e| MatrixAdapterError::SessionLoad(e.to_string()))?
            }
        };
        let store = StoolapSessionStore::new(&resolved)
            .map_err(|e| MatrixAdapterError::SessionLoad(e.to_string()))?;
        let rows = store
            .get_all_sessions()
            .await
            .map_err(|e| MatrixAdapterError::SessionLoad(e.to_string()))?;
        Ok(rows
            .into_iter()
            .map(|r| (r.user_id, r.device_id, r.homeserver_url))
            .collect())
    }
}

