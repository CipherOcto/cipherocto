#[no_mangle]
/// # Safety
/// `config` must point to a valid buffer of at least `len` bytes.
pub unsafe extern "C" fn create_adapter(config: *const u8, config_len: usize) -> *mut () {
    if config.is_null() || config_len == 0 {
        set_last_error(MatrixAdapterError::SessionLoad("null config".into()));
        return std::ptr::null_mut();
    }

    let config_bytes = std::slice::from_raw_parts(config, config_len);
    match MatrixAdapter::from_config_bytes(config_bytes) {
        Ok(adapter) => {
            // Clear the last error on a successful construction.
            set_last_error_success();
            Box::into_raw(Box::new(adapter)) as *mut ()
        }
        Err(e) => {
            set_last_error(e);
            std::ptr::null_mut()
        }
    }
}

/// Stash the most recent adapter-construction error so a host that
/// got a null pointer from `create_adapter` can read a stable error
/// string. R1-L14: the previous shape discarded the error entirely.
fn set_last_error(e: MatrixAdapterError) {
    LAST_ERROR.with(|slot| {
        *slot.borrow_mut() = Some(e.to_string());
    });
}

fn set_last_error_success() {
    LAST_ERROR.with(|slot| {
        *slot.borrow_mut() = None;
    });
}

thread_local! {
    static LAST_ERROR: std::cell::RefCell<Option<String>> = const { std::cell::RefCell::new(None) };
}

#[no_mangle]
/// Return the most recent adapter-construction error as a
/// heap-allocated C string. The caller MUST free the returned
/// pointer with `free_last_error`. Returns null on success.
pub extern "C" fn last_error() -> *mut std::os::raw::c_char {
    LAST_ERROR.with(|slot| {
        slot.borrow()
            .as_ref()
            .map(|s| {
                // The pointer is null-terminated; the caller is
                // responsible for freeing it via `free_last_error`.
                std::ffi::CString::new(s.as_str())
                    .map(|c| c.into_raw())
                    .unwrap_or(std::ptr::null_mut())
            })
            .unwrap_or(std::ptr::null_mut())
    })
}

#[no_mangle]
/// # Safety
/// `ptr` must be a pointer previously returned from `last_error`, or
/// null.
pub unsafe extern "C" fn free_last_error(ptr: *mut std::os::raw::c_char) {
    if !ptr.is_null() {
        let _ = std::ffi::CString::from_raw(ptr);
    }
}

#[no_mangle]
/// # Safety
/// `ptr` must be a pointer previously returned by `create_adapter`.
pub unsafe extern "C" fn destroy_adapter(adapter: *mut ()) {
    if !adapter.is_null() {
        let _ = Box::from_raw(adapter as *mut MatrixAdapter);
    }
}

/// RR2: writeback export. The cdylib exposes `persist_session_to_disk`
/// so a C-only host can drive token-rotation writeback without
/// going through Rust. The return value is a status code:
///
/// - `0` = success. `*out_written` is `1` if the on-disk file was
///   actually updated, or `0` if the writeback was a no-op
///   (rotated pair equal to on-disk) or was suppressed because
///   another process holds the lock (`WritebackError::LockHeld`
///   is non-fatal and surfaces as `Ok(written: false)` — the
///   host can retry on the next cycle). R4-L1 collapsed the
///   previously-promised status `1` (LockHeld) into status `0`
///   because `MatrixAdapter::persist_session_to_disk` already
///   treats LockHeld as a no-op success before the C ABI sees it.
/// - `2` = `SnapshotMismatch` (refused — on-disk contents drifted
///   since startup, AND both the per-call `_force_writeback` AND
///   the config-level `force_writeback` were false; R6-M1 changed
///   the Rust method's semantics so the per-call argument is OR'd
///   with the config-level setting, but the `SnapshotMismatch`
///   error only fires when the OR collapses to false).
/// - `3` = `FileMissing` (refused — file disappeared between
///   startup and writeback).
/// - `4` = `Io` / `Serialize` / generic writeback failure.
/// - `6` = `InvalidArg` (`adapter` was null).
///
/// Status codes `1` and `5` are NOT emitted by the current
/// implementation: `1` was the pre-R4 `LockHeld` code (R4-L1
/// collapsed it into `0` because the host can treat
/// `status == 0 && *out_written == 0` as a no-op retry
/// regardless of the cause), and `5` is reserved/unused. R10-L2:
/// a previous version of this docstring silently skipped both
/// codes; if a host ever observes status `1` or `5` it is a bug
/// in this crate (the status enum is `{0, 2, 3, 4, 6}` and any
/// other value would have to be added with a documented
/// mapping). The reserved range is preserved for a future
/// `C ABI v2` that splits `LockHeld` out of the success path
/// (planned but not yet implemented).
///
/// The `written` flag is returned via `*out_written` (1 if the
/// file was actually updated, 0 if it was a no-op or a refused
/// write — but refused writes return non-zero status, so a
/// non-zero status implies `*out_written` is undefined and the
/// host should treat it as 0).
///
/// # Safety
/// `adapter` must be a pointer previously returned by
/// `create_adapter`. `out_written` may be null; if non-null, it
/// must point to a writable `u8` slot.
#[no_mangle]
pub unsafe extern "C" fn persist_session_to_disk(
    adapter: *mut (),
    _force_writeback: u8,
    out_written: *mut u8,
) -> i32 {
    if adapter.is_null() {
        return 6; // InvalidArg
    }
    let adapter = &*(adapter as *const MatrixAdapter);
    // R6-M1: forward the host's `_force_writeback` flag to
    // `MatrixAdapter::persist_session_to_disk`. The Rust method
    // ORs the per-call override with the config-level
    // `force_writeback` setting, so a host that wants the default
    // config-level behavior should pass 0. Previous shape: this
    // parameter was accepted by the C ABI but dropped on the
    // floor (the Rust call took no args), so a host that set
    // `_force_writeback = 1` got the same behavior as `_force_writeback
    // = 0`. That made the C ABI surface lie about what it would do.
    let outcome_result = adapter
        .persist_session_to_disk(_force_writeback != 0)
        .map(|o| o.written);
    match outcome_result {
        Ok(written) => {
            // R4-L1: this branch is the only success path. It
            // covers BOTH the actual writeback (`written = true`)
            // AND the two no-op cases: the rotated-pair-equal
            // fast path and `WritebackError::LockHeld` (which
            // `MatrixAdapter::persist_session_to_disk` translates
            // to `Ok(written: false)` before we get here). Host
            // code should treat `status == 0 && *out_written == 0`
            // as "rotated pair not persisted, try again later"
            // without distinguishing the two no-op causes.
            if !out_written.is_null() {
                *out_written = if written { 1 } else { 0 };
            }
            0
        }
        Err(MatrixAdapterError::WritebackFailed(msg)) => {
            // Map the inner WritebackError to a status code by
            // re-classifying the message. The MatrixAdapterError
            // path collapses the typed WritebackError into a
            // String, so we pattern-match on the string prefix
            // that `WritebackError::Display` produces (this is
            // a stopgap until we plumb the typed error through).
            //
            // R3-M3: each branch matches a distinctive substring
            // unique to one variant's Display. The previous code
            // matched on `"lock"`, which also matched unrelated
            // io errors like `"open lock file: permission denied"`
            // and misclassified them as LockHeld (status 1 = retry
            // success), hiding the real failure from the host.
            //
            // R4-L1: the `"is held by another process"` arm was
            // removed — `MatrixAdapter::persist_session_to_disk`
            // translates `WritebackError::LockHeld` to
            // `Ok(written: false)` before the C ABI sees it, so
            // this substring can never appear in `msg`. The arm
            // was dead code.
            if msg.contains("contents changed; refusing to overwrite") {
                2
            } else if msg.contains("disappeared between startup and writeback") {
                3
            } else {
                4 // Io or generic writeback failure
            }
        }
        Err(_) => 4,
    }
}

