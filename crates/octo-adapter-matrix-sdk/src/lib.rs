//! Matrix adapter for DOT using matrix-rust-sdk (RFC-0850 S8.1, PlatformType::Matrix)
//!
//! This adapter replaces the in-house reqwest-based Matrix adapter with the
//! official matrix-rust-sdk for better federation support, media handling,
//! and long-term maintenance.
//!
//! Exports C ABI functions (`adapter_version`, `platform_type`, `create_adapter`,
//! `destroy_adapter`) for dynamic loading as a cdylib plugin.
//!
//! Matrix is the most aligned platform for CipherOcto — it is itself federated
//! and decentralized, matching CipherOcto's architecture.
//!
//! ## Configuration
//!
//! ```json
//! {
//!   "homeserver_url": "https://matrix.example.com",
//!   "user_id": "@bot:matrix.example.com",
//!   "device_id": "MYDEVICEID",
//!   "access_token": "syt_xxx",
//!   "refresh_token": "syr_xxx",
//!   "rooms": ["!abcdef:example.com"]
//! }
//! ```
//!
//! The `user_id`, `device_id`, and `access_token` fields are required and
//! match the session material captured by `octo-matrix-onboard` (mission
//! 0850h-a). The optional `refresh_token` is populated when the homeserver
//! issues one; the adapter uses it to refresh `access_token` in-memory on
//! 401. Configs produced before mission 0850h-a (which had only
//! `homeserver_url`/`access_token`/`rooms`) MUST be re-generated by running
//! `octo-matrix-onboard login` — old configs will fail to deserialize.

